#!/usr/bin/env python3
"""Press every position of the button matrix and report what changes.

For each row/column: reset the machine, boot, press the key, look at the
OLED and the LED outputs, release it, look again. Everything is compared with
a baseline boot without keys. Also measures the blink period of LED outputs
that flash on their own.

    make matrix-sweep            -> build/reports/matrix_sweep.md

Renode runs headless with its monitor on TCP; virtual time only advances
when the script asks for it, so results are repeatable.
"""

import argparse
import os
import re
import socket
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RENODE = os.environ.get("RENODE", "/opt/renode_1.17.0-portable/renode")
PROMPT = b"(mpk) "
REPORT = ROOT / "build" / "reports" / "matrix_sweep.md"


class Monitor:
    def __init__(self, port):
        for _ in range(300):
            try:
                self.sock = socket.create_connection(("127.0.0.1", port), timeout=1)
                break
            except OSError:
                time.sleep(0.1)
        else:
            sys.exit("could not connect to the Renode monitor")
        self.buffer = b""
        self.read(timeout=60)

    def read(self, timeout=120):
        self.sock.settimeout(timeout)
        while PROMPT not in self.buffer:
            data = self.sock.recv(65536)
            if not data:
                break
            self.buffer += data
        head, _, self.buffer = self.buffer.partition(PROMPT)
        return re.sub(rb"\xff[\xfb-\xfe].", b"", head).decode(errors="replace")

    def __call__(self, command):
        self.sock.sendall(command.encode() + b"\n")
        lines = [l for l in self.read().replace("\r", "").split("\n") if l.strip()]
        if lines and lines[0].strip().endswith(command):
            lines = lines[1:]
        return "\n".join(lines).strip()

    def run(self, seconds):
        self(f'emulation RunFor "{seconds}"')

    def screen(self):
        return [l for l in self("spi2.oled AsciiArt").splitlines() if re.fullmatch(r"[.#]+", l)]

    def leds(self):
        return [int(v) for v in self("spi1.leds Brightness").split()]


def text_screen(rows):
    """OLED rows as compact text (two pixel rows per line, block characters)."""
    out = []
    for y in range(0, len(rows), 2):
        top, bottom = rows[y], rows[y + 1] if y + 1 < len(rows) else "." * len(rows[y])
        out.append("".join({("#", "#"): "█", ("#", "."): "▀", (".", "#"): "▄"}.get((a, b), " ")
                           for a, b in zip(top, bottom)).rstrip())
    while out and not out[-1]:
        out.pop()
    return out


def led_changes(base, now, threshold=10):
    return [(k, b, n) for k, (b, n) in enumerate(zip(base, now)) if abs(b - n) >= threshold]


def blink_periods(mon, outputs, seconds=2.0, step=0.02):
    """Sample outputs over time; return {output: (period s, duty)} for blinkers."""
    raw = {k: [] for k in outputs}
    for _ in range(int(seconds / step)):
        mon.run(step)
        values = mon.leds()
        for k in outputs:
            raw[k].append(values[k])
    result = {}
    for k, values in raw.items():
        low, high = min(values), max(values)
        if high - low < 5:
            continue
        s = [v > (low + high) / 2 for v in values]
        rises = [i for i in range(1, len(s)) if s[i] and not s[i - 1]]
        if len(rises) >= 2:
            period = (rises[-1] - rises[0]) / (len(rises) - 1) * step
            result[k] = (period, sum(s) / len(s))
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--port", type=int, default=4377)
    parser.add_argument("--boot", type=float, default=3.0, help="virtual seconds to boot")
    parser.add_argument("--hold", type=float, default=0.4, help="virtual seconds to hold a key")
    parser.add_argument("--rows", type=int, default=13)
    parser.add_argument("--columns", type=int, default=6)
    args = parser.parse_args()

    renode = subprocess.Popen(
        [RENODE, "--disable-gui", "--plain", "--port", str(args.port), "-e",
         "include @sim/mpk.resc; include @sim/quiet.resc"],
        cwd=ROOT, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    try:
        mon = Monitor(args.port)
        mon.run(args.boot)
        base_screen, base_leds = mon.screen(), mon.leds()
        blinkers = blink_periods(mon, [k for k in range(len(base_leds))])

        lines = ["# Button matrix sweep", "",
                 "Generated by `make matrix-sweep`. Each position is pressed on a "
                 f"freshly booted machine ({args.boot} s), held {args.hold} s, then "
                 "released. Changes are relative to the baseline below.", "",
                 "## Baseline", "", "```", *text_screen(base_screen), "```", "",
                 "Lit LED outputs: " + ", ".join(f"{k} ({v} %)" for k, v in enumerate(base_leds) if v),
                 ""]
        if blinkers:
            lines += ["Blinking outputs: " + ", ".join(
                f"{k} (period {p:.2f} s = {60 / p:.0f} per minute, on {d:.0%})"
                for k, (p, d) in blinkers.items()), ""]

        summary = []
        for r in range(args.rows):
            for c in range(args.columns):
                mon("machine Reset")
                mon.run(args.boot)
                mon(f"keys Press {r} {c}")
                mon.run(args.hold)
                held_screen, held_leds = mon.screen(), mon.leds()
                mon(f"keys Release {r} {c}")
                mon.run(0.5)
                after_screen, after_leds = mon.screen(), mon.leds()
                print(f"row {r} column {c} done", file=sys.stderr)

                changes = []
                lines += [f"## Row {r}, column {c} (PC{8 + c})", ""]
                for label, screen, leds in (("held", held_screen, held_leds),
                                            ("released", after_screen, after_leds)):
                    led_diff = led_changes(base_leds, leds)
                    if screen != base_screen:
                        lines += [f"Screen while {label}:", "", "```", *text_screen(screen), "```", ""]
                        changes.append(f"screen ({label})")
                    if led_diff:
                        lines.append(f"LEDs while {label}: " + ", ".join(
                            f"{k}: {b} → {n} %" for k, b, n in led_diff))
                        lines.append("")
                        changes.append(f"LEDs {','.join(str(k) for k, _, _ in led_diff)} ({label})")
                if not changes:
                    lines += ["No visible change.", ""]
                summary.append((r, c, "; ".join(changes) or "—"))

        lines[lines.index("## Baseline"):lines.index("## Baseline")] = [
            "## Summary", "", "| Row | Column | Visible effect |", "|---|---|---|",
            *[f"| {r} | {c} (PC{8 + c}) | {e} |" for r, c, e in summary], ""]
        REPORT.parent.mkdir(parents=True, exist_ok=True)
        REPORT.write_text("\n".join(lines) + "\n")
        print(f"report: {REPORT.relative_to(ROOT)}")
    finally:
        try:
            mon("quit")
        except Exception:
            pass
        renode.terminate()
        renode.wait(10)


if __name__ == "__main__":
    main()
