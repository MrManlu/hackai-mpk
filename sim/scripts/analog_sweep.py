#!/usr/bin/env python3
"""Drive every analog input (ADC channel x multiplexer position) and report
what changes on the OLED and the LEDs.

For each input: reset, boot, set the input to `--value` for a while, look,
set it back to 0, look again. Compared with a baseline boot.

    make analog-sweep            -> build/reports/analog_sweep.md
"""

import argparse
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from matrix_sweep import RENODE, ROOT, Monitor, led_changes, text_screen  # noqa: E402

REPORT = ROOT / "build" / "reports" / "analog_sweep.md"


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--port", type=int, default=4376)
    parser.add_argument("--boot", type=float, default=3.0)
    parser.add_argument("--hold", type=float, default=0.4)
    parser.add_argument("--value", type=int, default=4095)
    parser.add_argument("--channels", type=int, default=5)
    parser.add_argument("--mux", type=int, default=8)
    args = parser.parse_args()

    renode = subprocess.Popen(
        [RENODE, "--disable-gui", "--plain", "--port", str(args.port), "-e",
         "include @sim/mpk.resc; include @sim/quiet.resc"],
        cwd=ROOT, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    mon = None
    try:
        mon = Monitor(args.port)
        mon.run(args.boot)
        base_screen, base_leds = mon.screen(), mon.leds()
        lines = ["# Analog input sweep", "",
                 f"Generated by `make analog-sweep`. Each input is set to {args.value} "
                 f"for {args.hold} s on a fresh boot, then back to 0.", "",
                 "## Baseline", "", "```", *text_screen(base_screen), "```", ""]
        summary = []
        for ch in range(args.channels):
            for mux in range(args.mux):
                mon("machine Reset")
                mon("adc1 Reset")
                mon.run(args.boot)
                mon(f"adc1 SetInput {ch} {mux} {args.value}")
                mon.run(args.hold)
                held_screen, held_leds = mon.screen(), mon.leds()
                mon(f"adc1 SetInput {ch} {mux} 0")
                mon.run(0.5)
                after_screen, after_leds = mon.screen(), mon.leds()
                print(f"channel {ch} mux {mux} done", file=sys.stderr)

                changes = []
                lines += [f"## Channel {ch} (PA{ch}), mux {mux}", ""]
                for label, screen, leds in (("high", held_screen, held_leds),
                                            ("back to 0", after_screen, after_leds)):
                    diff = led_changes(base_leds, leds)
                    if screen != base_screen:
                        lines += [f"Screen ({label}):", "", "```", *text_screen(screen), "```", ""]
                        changes.append(f"screen ({label})")
                    if diff:
                        lines += [f"LEDs ({label}): " + ", ".join(f"{k}: {b} → {n} %" for k, b, n in diff), ""]
                        changes.append(f"LEDs {','.join(str(k) for k, _, _ in diff)} ({label})")
                if not changes:
                    lines += ["No visible change.", ""]
                summary.append((ch, mux, "; ".join(changes) or "—"))

        at = lines.index("## Baseline")
        lines[at:at] = ["## Summary", "", "| Channel | Mux | Visible effect |", "|---|---|---|",
                        *[f"| {c} (PA{c}) | {m} | {e} |" for c, m, e in summary], ""]
        REPORT.parent.mkdir(parents=True, exist_ok=True)
        REPORT.write_text("\n".join(lines) + "\n")
        print(f"report: {REPORT.relative_to(ROOT)}")
    finally:
        if mon:
            try:
                mon("quit")
            except Exception:
                pass
        renode.terminate()
        renode.wait(10)


if __name__ == "__main__":
    main()
