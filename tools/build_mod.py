#!/usr/bin/env python3
"""build_mod: build the hackai-mpk firmware from the stock image and firmware/.

    build_mod.py [--out build/mods/hackai.bin] [--firmware baserom/firmware.bin]

1. Generates build/mods/stock.ld from config/symbols.csv: every stock function
   and label becomes a linker symbol (functions with the Thumb bit set).
2. Compiles firmware/src/*.c with arm-none-eabi-gcc and links them with
   firmware/link.ld: code at 0x08026000, in the free area after the application.
3. Copies the code into a copy of the stock image, fills our settings sector
   (0x0802D800-0x0802DFFF) with 0xFF (erased), and applies firmware/hooks.toml:
   the first 4 bytes of each replaced stock function become a B.W to ours.
4. Runs the mpkflash safety checks.

Writes the image, plus .elf, .map and a disassembly next to it. See
docs/patching.md.
"""

import argparse
import csv
import re
import subprocess
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
import mpkflash  # noqa: E402

FIRMWARE = ROOT / "firmware"
BASE = 0x08000000
CODE = (0x08026000, 0x0802D800)       # must match firmware/link.ld
SETTINGS = (0x0802D800, 0x0802E000)   # our settings sector, erased in the image
APP_END = 0x08025D4C                  # end of the stock application
CFLAGS = ["-mcpu=cortex-m4", "-mthumb", "-Os", "-std=c11", "-ffreestanding", "-nostdlib",
          "-fno-common", "-ffunction-sections", "-fdata-sections", "-Wall", "-Wextra",
          "-Werror", "-g"]


def run(cmd, **kw):
    result = subprocess.run(cmd, capture_output=True, text=True, **kw)
    if result.returncode:
        sys.stderr.write(result.stdout + result.stderr)
        raise RuntimeError(f"failed: {' '.join(map(str, cmd[:3]))} ...")
    return result.stdout


def stock_symbols():
    symbols = {}
    with open(ROOT / "config" / "symbols.csv", newline="") as f:
        for row in csv.DictReader(f):
            name, kind = row["name"], row["kind"]
            if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", name):
                continue
            address = int(row["address"], 16)
            symbols[name] = (address, kind)
    return symbols


def write_stock_ld(symbols, path):
    lines = ["/* Generated by tools/build_mod.py from config/symbols.csv. Do not edit. */"]
    for name, (address, kind) in sorted(symbols.items(), key=lambda s: s[1][0]):
        value = address | 1 if kind == "func" else address
        lines.append(f"PROVIDE({name} = 0x{value:08X});")
    path.write_text("\n".join(lines) + "\n")


def b_w(at, target):
    """Thumb-2 B.W (encoding T4) from `at` to `target`."""
    offset = target - (at + 4)
    if offset % 2 or not -(1 << 24) <= offset < (1 << 24):
        raise RuntimeError(f"B.W from 0x{at:08X} to 0x{target:08X} out of range")
    s = (offset >> 24) & 1
    i1, i2 = (offset >> 23) & 1, (offset >> 22) & 1
    j1, j2 = (~i1 ^ s) & 1, (~i2 ^ s) & 1
    hw1 = 0xF000 | (s << 10) | ((offset >> 12) & 0x3FF)
    hw2 = 0x9000 | (j1 << 13) | (j2 << 11) | ((offset >> 1) & 0x7FF)
    return hw1.to_bytes(2, "little") + hw2.to_bytes(2, "little")


def elf_symbols(elf):
    symbols = {}
    for line in run(["arm-none-eabi-nm", str(elf)]).splitlines():
        parts = line.split()
        if len(parts) == 3:
            symbols[parts[2]] = int(parts[0], 16)
    return symbols


def build(out, firmware):
    stock = Path(firmware).read_bytes()
    if stock != mpkflash.STOCK.read_bytes():
        print("note: patching an image that is not baserom/firmware.bin")
    work = Path(out).parent
    work.mkdir(parents=True, exist_ok=True)
    symbols = stock_symbols()
    write_stock_ld(symbols, work / "stock.ld")

    hooks = tomllib.loads((FIRMWARE / "hooks.toml").read_text()).get("replace", [])
    sources = sorted((FIRMWARE / "src").glob("*.c"))
    elf = Path(out).with_suffix(".elf")
    keep = [f"-Wl,--undefined={h['with']}" for h in hooks]
    run(["arm-none-eabi-gcc", *CFLAGS, f"-I{FIRMWARE / 'include'}", *map(str, sources),
         "-T", str(FIRMWARE / "link.ld"), f"-L{work}", "-Wl,--gc-sections",
         f"-Wl,-Map={elf.with_suffix('.map')}", *keep, "-o", str(elf)])
    code_bin = elf.with_suffix(".code.bin")
    run(["arm-none-eabi-objcopy", "-O", "binary", "-j", ".text", str(elf), str(code_bin)])
    (elf.with_suffix(".lst")).write_text(run(["arm-none-eabi-objdump", "-d", "-S", str(elf)]))
    code = code_bin.read_bytes()
    if CODE[0] + len(code) > CODE[1]:
        raise RuntimeError(f"code is {len(code)} bytes, more than the {CODE[1] - CODE[0]} available")

    image = bytearray(stock)
    region = image[APP_END - BASE:SETTINGS[1] - BASE]
    if any(region[CODE[0] - APP_END:]) and stock == mpkflash.STOCK.read_bytes():
        raise RuntimeError("the free area of the stock image is not empty")
    image[CODE[0] - BASE:CODE[0] - BASE + len(code)] = code
    image[SETTINGS[0] - BASE:SETTINGS[1] - BASE] = b"\xff" * (SETTINGS[1] - SETTINGS[0])

    ours = elf_symbols(elf)
    for hook in hooks:
        name, target = hook["function"], hook["with"]
        if name not in symbols or symbols[name][1] != "func":
            raise RuntimeError(f"hooks.toml: {name} is not a function in config/symbols.csv")
        if target not in ours:
            raise RuntimeError(f"hooks.toml: {target} is not defined in firmware/src")
        at, to = symbols[name][0], ours[target] & ~1
        image[at - BASE:at - BASE + 4] = b_w(at, to)
        print(f"hook: {name} (0x{at:08X}) -> {target} (0x{to:08X})")

    errors, warnings = mpkflash.check_image(bytes(image), mpkflash.STOCK.read_bytes())
    for w in warnings:
        print("warning:", w)
    if errors:
        for e in errors:
            print("ERROR:", e)
        raise RuntimeError("the image is not safe to flash")
    Path(out).write_bytes(image)
    print(f"code: {len(code)} bytes at 0x{CODE[0]:08X} "
          f"({CODE[1] - CODE[0] - len(code)} bytes left)")
    print(f"wrote {out} (passes the mpkflash checks)")


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--out", default=str(ROOT / "build" / "mods" / "hackai.bin"))
    parser.add_argument("--firmware", default=str(mpkflash.STOCK))
    args = parser.parse_args()
    build(args.out, args.firmware)


if __name__ == "__main__":
    try:
        main()
    except (RuntimeError, OSError) as e:
        sys.exit(f"error: {e}")
