#!/usr/bin/env python3
"""build_mod: build the hackai-mpk firmware from the stock image and firmware/.

    build_mod.py [--out build/mods/hackai.bin] [--firmware baserom/firmware.bin]

1. Generates build/mods/stock.ld from config/symbols.csv: every stock function
   and label becomes a linker symbol (functions with the Thumb bit set).
2. Compiles firmware/src/*.c with arm-none-eabi-gcc and links them with
   firmware/link.ld: code at 0x08026000, in the free area after the application.
3. Copies the code into a copy of the stock image, fills our settings sector
   (0x0802D800-0x0802DFFF) with 0xFF (erased), and applies firmware/hooks.toml:
   - [[replace]]: the first 4 bytes of a stock function become a B.W to ours;
   - [[wrap]]: the same, and our code can still call the stock function as
     `<function>_original` (a trampoline with the displaced instructions,
     generated in build/mods/trampolines.S);
   - [[jump]]: one 4-byte instruction anywhere becomes a B.W to our code
     (`expect` gives the bytes it must replace; our code returns by itself).
4. Runs the mpkflash safety checks.

Writes the image, plus .elf, .map and a disassembly next to it. See
docs/patching.md.
"""

import argparse
import csv
import re
import subprocess
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
import mpkflash  # noqa: E402

FIRMWARE = ROOT / "firmware"
BASE = 0x08000000
CODE = (0x08026000, 0x0802D800)       # must match firmware/link.ld
SETTINGS = (0x0802D800, 0x0802E000)   # our settings sector, erased in the image
APP_END = 0x08025D4C                  # end of the stock application
CFLAGS = ["-mcpu=cortex-m4", "-mthumb", "-Os", "-std=c11", "-ffreestanding", "-nostdlib",
          "-fno-common", "-ffunction-sections", "-fdata-sections", "-Wall", "-Wextra",
          "-Werror", "-g"]


def run(cmd, **kw):
    result = subprocess.run(cmd, capture_output=True, text=True, **kw)
    if result.returncode:
        sys.stderr.write(result.stdout + result.stderr)
        raise RuntimeError(f"failed: {' '.join(map(str, cmd[:3]))} ...")
    return result.stdout


def stock_symbols():
    symbols = {}
    with open(ROOT / "config" / "symbols.csv", newline="") as f:
        for row in csv.DictReader(f):
            name, kind = row["name"], row["kind"]
            if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", name):
                continue
            address = int(row["address"], 16)
            symbols[name] = (address, kind)
    return symbols


def write_stock_ld(symbols, path):
    lines = ["/* Generated by tools/build_mod.py from config/symbols.csv. Do not edit. */"]
    for name, (address, kind) in sorted(symbols.items(), key=lambda s: s[1][0]):
        value = address | 1 if kind == "func" else address
        lines.append(f"PROVIDE({name} = 0x{value:08X});")
    path.write_text("\n".join(lines) + "\n")


def b_w(at, target):
    """Thumb-2 B.W (encoding T4) from `at` to `target`."""
    offset = target - (at + 4)
    if offset % 2 or not -(1 << 24) <= offset < (1 << 24):
        raise RuntimeError(f"B.W from 0x{at:08X} to 0x{target:08X} out of range")
    s = (offset >> 24) & 1
    i1, i2 = (offset >> 23) & 1, (offset >> 22) & 1
    j1, j2 = (~i1 ^ s) & 1, (~i2 ^ s) & 1
    hw1 = 0xF000 | (s << 10) | ((offset >> 12) & 0x3FF)
    hw2 = 0x9000 | (j1 << 13) | (j2 << 11) | ((offset >> 1) & 0x7FF)
    return hw1.to_bytes(2, "little") + hw2.to_bytes(2, "little")


def thumb_instructions(data, at, minimum):
    """Whole Thumb instructions starting at `at` covering at least `minimum`
    bytes: [(address, bytes)]."""
    out, n = [], 0
    while n < minimum:
        hw = int.from_bytes(data[at - BASE + n:at - BASE + n + 2], "little")
        size = 4 if hw >> 11 in (0b11101, 0b11110, 0b11111) else 2
        out.append((at + n, data[at - BASE + n:at - BASE + n + size]))
        n += size
    return out


def pc_relative(code):
    """True if a Thumb instruction depends on its address (literal loads,
    branches, ADR, CBZ, IT blocks): it cannot be moved to a trampoline."""
    hw1 = int.from_bytes(code[:2], "little")
    if len(code) == 2:
        return (hw1 & 0xF800 in (0x4800, 0xA000, 0xE000)          # LDR lit, ADR, B
                or hw1 & 0xF000 == 0xD000                         # Bcc, SVC
                or hw1 & 0xF500 == 0xB100                         # CBZ/CBNZ
                or hw1 & 0xFF00 == 0xBF00 and hw1 & 0x000F       # IT
                or hw1 & 0xFF87 == 0x4487 or hw1 & 0xFF78 == 0x4478)  # ADD/MOV with PC
    hw2 = int.from_bytes(code[2:4], "little")
    return (hw1 & 0xF800 == 0xF000 and hw2 & 0x8000              # B.W, BL, Bcc.W
            or hw1 & 0xFE0F == 0xF80F or hw1 & 0xFE0F == 0xF90F  # LDR*.W with Rn = PC
            or hw1 & 0xFE5F == 0xE85F                            # LDRD literal
            or hw1 & 0xFBEF == 0xF20F or hw1 & 0xFBEF == 0xF2AF  # ADR.W
            or hw1 & 0xFFF0 == 0xE8D0 and hw2 & 0xFFE0 == 0xF000  # TBB/TBH
            or hw1 & 0x000F == 0xF and hw1 & 0xFE00 == 0xE800)   # other PC-based


def write_trampolines(stock, symbols, wraps, path):
    lines = ["@ Generated by tools/build_mod.py from firmware/hooks.toml. Do not edit.",
             "    .syntax unified", "    .thumb"]
    for hook in wraps:
        name = hook["function"]
        at = function_address(symbols, name)
        moved = thumb_instructions(stock, at, 4)
        for address, code in moved:
            if pc_relative(code):
                raise RuntimeError(f"hooks.toml: cannot wrap {name}: the instruction at "
                                   f"0x{address:08X} ({code.hex(' ')}) depends on its address")
        back = moved[-1][0] + len(moved[-1][1])
        lines += ["", f"    .section .text.{name}_original", f"    .global {name}_original",
                  "    .thumb_func", f"{name}_original:",
                  f"    @ instructions moved from 0x{at:08X}, then back to 0x{back:08X}"]
        for address, code in moved:
            halfwords = ", ".join(f"0x{int.from_bytes(code[i:i + 2], 'little'):04X}"
                                  for i in range(0, len(code), 2))
            lines.append(f"    .hword {halfwords}    @ 0x{address:08X}")
        lines += [f"    ldr.w pc, =0x{back | 1:08X}", "    .ltorg"]
    path.write_text("\n".join(lines) + "\n")


def function_address(symbols, name):
    if name not in symbols or symbols[name][1] != "func":
        raise RuntimeError(f"hooks.toml: {name} is not a function in config/symbols.csv")
    return symbols[name][0]


def elf_symbols(elf):
    symbols = {}
    for line in run(["arm-none-eabi-nm", str(elf)]).splitlines():
        parts = line.split()
        if len(parts) == 3:
            symbols[parts[2]] = int(parts[0], 16)
    return symbols


def build(out, firmware):
    stock = Path(firmware).read_bytes()
    if stock != mpkflash.STOCK.read_bytes():
        print("note: patching an image that is not baserom/firmware.bin")
    work = Path(out).parent
    work.mkdir(parents=True, exist_ok=True)
    symbols = stock_symbols()
    write_stock_ld(symbols, work / "stock.ld")

    config = tomllib.loads((FIRMWARE / "hooks.toml").read_text())
    replaces, wraps, jumps = (config.get(k, []) for k in ("replace", "wrap", "jump"))
    write_trampolines(stock, symbols, wraps, work / "trampolines.S")
    sources = (sorted((FIRMWARE / "src").glob("*.c")) + sorted((FIRMWARE / "src").glob("*.S"))
               + [work / "trampolines.S"])
    elf = Path(out).with_suffix(".elf")
    keep = [f"-Wl,--undefined={h['with']}" for h in replaces + wraps]
    keep += [f"-Wl,--undefined={h['to']}" for h in jumps]
    run(["arm-none-eabi-gcc", *CFLAGS, f"-I{FIRMWARE / 'include'}", *map(str, sources),
         "-T", str(FIRMWARE / "link.ld"), f"-L{work}", "-Wl,--gc-sections",
         f"-Wl,-Map={elf.with_suffix('.map')}", *keep, "-o", str(elf)])
    code_bin = elf.with_suffix(".code.bin")
    run(["arm-none-eabi-objcopy", "-O", "binary", "-j", ".text", str(elf), str(code_bin)])
    (elf.with_suffix(".lst")).write_text(run(["arm-none-eabi-objdump", "-d", "-S", str(elf)]))
    code = code_bin.read_bytes()
    if CODE[0] + len(code) > CODE[1]:
        raise RuntimeError(f"code is {len(code)} bytes, more than the {CODE[1] - CODE[0]} available")

    image = bytearray(stock)
    region = image[APP_END - BASE:SETTINGS[1] - BASE]
    if any(region[CODE[0] - APP_END:]) and stock == mpkflash.STOCK.read_bytes():
        raise RuntimeError("the free area of the stock image is not empty")
    image[CODE[0] - BASE:CODE[0] - BASE + len(code)] = code
    image[SETTINGS[0] - BASE:SETTINGS[1] - BASE] = b"\xff" * (SETTINGS[1] - SETTINGS[0])

    ours = elf_symbols(elf)

    def ours_address(target):
        if target not in ours:
            raise RuntimeError(f"hooks.toml: {target} is not defined in firmware/src")
        return ours[target] & ~1

    for kind, hooks in (("replace", replaces), ("wrap", wraps)):
        for hook in hooks:
            name, target = hook["function"], hook["with"]
            at, to = function_address(symbols, name), ours_address(target)
            image[at - BASE:at - BASE + 4] = b_w(at, to)
            print(f"{kind}: {name} (0x{at:08X}) -> {target} (0x{to:08X})")
    for hook in jumps:
        at, to = int(hook["at"], 16), ours_address(hook["to"])
        expect = bytes.fromhex(hook["expect"])
        found = bytes(stock[at - BASE:at - BASE + 4])
        if len(expect) != 4 or found != expect:
            raise RuntimeError(f"hooks.toml: at 0x{at:08X} expected {hook['expect']}, "
                               f"found {found.hex(' ')}")
        image[at - BASE:at - BASE + 4] = b_w(at, to)
        print(f"jump: 0x{at:08X} -> {hook['to']} (0x{to:08X})")

    errors, warnings = mpkflash.check_image(bytes(image), mpkflash.STOCK.read_bytes())
    for w in warnings:
        print("warning:", w)
    if errors:
        for e in errors:
            print("ERROR:", e)
        raise RuntimeError("the image is not safe to flash")
    Path(out).write_bytes(image)
    print(f"code: {len(code)} bytes at 0x{CODE[0]:08X} "
          f"({CODE[1] - CODE[0] - len(code)} bytes left)")
    print(f"wrote {out} (passes the mpkflash checks)")


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--out", default=str(ROOT / "build" / "mods" / "hackai.bin"))
    parser.add_argument("--firmware", default=str(mpkflash.STOCK))
    args = parser.parse_args()
    build(args.out, args.firmware)


if __name__ == "__main__":
    try:
        main()
    except (RuntimeError, OSError) as e:
        sys.exit(f"error: {e}")
